    function segment_index(yw : integer) return integer is
        variable s : integer;
    begin
        s := yw / COORD_SEG_H;

        if s < 0 then
            return 0;
        elsif s >= COORD_SEGMENTS then
            return COORD_SEGMENTS - 1;
        else
            return s;
        end if;
    end function;

    function path_left_center_x(
        path_id : path_id_t;
        yw      : integer
    ) return integer is
    begin
        return LEFT_PATHS(path_id)(segment_index(yw));
    end function;

    function path_right_center_x(
        path_id : path_id_t;
        yw      : integer
    ) return integer is
    begin
        return RIGHT_PATHS(path_id)(segment_index(yw));
    end function;

